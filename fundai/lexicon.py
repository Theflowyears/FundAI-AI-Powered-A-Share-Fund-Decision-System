def termness(word):
    """候选词是否为“完整金融术语”（必须在 FIN_TERMS 词表内逐字命中）。

    教训（audit 迭代）：允许“术语 + ≤2 字扩展/前缀滑窗”会把长公告句子切成
    “基金二级市场 / 盘时基金份额参 / 幅度溢价”这类滑动 n-gram 碎片；
    只学词表内完整术语（如 停牌/溢价/参考净值/临时停牌）才能得到用户认可的
    “完整词”。需要新领域词时直接向 FIN_TERMS 补充即可。
    """
    return bool(word) and word in FIN_TERMS


def denied(kw, txt, i):
    """判断 txt 中位于 i 处的关键词 kw 是否被否定修饰（前文含否定字）。"""
    window = txt[max(0, i - 6):i]
    return any(n in window for n in NEG_UNITS)


def signed_strength(label, strength):
    """把（标签, 强度）折算成**带符号**贡献：label 定方向，strength 视为强度。

    为什么需要（2026-09-11 修 BUG）：本项目历史上并存两种口径——
      * `semantics.infer_news()` 返回 `label=方向 + strength=正强度`（如 bear/4）；
      * `lexicon.score_text()` 返回 `strength=带符号`（如 bear/-3）。
    旧 `news.net_score` 直接 `raw += auto_strength`，于是**事件型利空被算成利多**：
    口径内 79,327 条消息（cbank_tight / geo_conflict / holder_flow 空头侧）强度全为正，
    十年 3674 天净情绪**从未出现负值**，消息分系统性只能看多。
    十年实测（`data/news_direction_study.py`）：按 label 取符号后，负值天数 0→1233、
    日级 Spearman −0.008→+0.048、净情绪最高 20% 的次日上涨率 50.5%→55.9%。

    中性/无关标签一律返回 0（不贡献方向）。
    """
    mag = abs(float(strength or 0))
    if label in ("bull", "big_bull"):
        return mag
    if label in ("bear", "big_bear"):
        return -mag
    return 0.0


def count_kw(txt, kws, strength):
    """统计 txt 中 kws 命中次数（跳过被否定修饰的命中），strength 为单次分值。"""
    total = 0
    for k in kws:
        pos = 0
        while True:
            i = txt.find(k, pos)
            if i < 0:
                break
            if not denied(k, txt, i):
                total += strength
            pos = i + len(k)
    return total


def relevant(txt):
    if any(k in txt for k in HARD_MACRO):
        return True
    return any(k in txt for k in MARKET_NOUNS)


def base_sentiment(txt):
    """纯词典情绪 → (bull, bear)。不计学习词。"""
    bs = count_kw(txt, BULL_STRONG, 3) + count_kw(txt, BULL_WEAK, 1)
    be = count_kw(txt, BEAR_STRONG, 3) + count_kw(txt, BEAR_WEAK, 1)
    # 明确利空“事件主导”校正：若命中了减持/冻结等事件词，即使残留弱利好词也不翻多
    if any(e in txt for e in EVENT_BEAR) and be >= 3:
        if bs < be * 2:
            bs = 0
    return bs, be


def score_text(txt, extra=None):
    """综合打分：词典 + 学习词叠加。

    extra: {word: (dir01, weight)}，dir01 ∈ {-1,1}，weight>0 加到对应方向。
    返回 dict：{bull, bear, net, relevance, label, strength}
    label ∈ bull/bear/neutral/irrelevant；strength 为净情绪分（带方向，截断 ±6）。
    """
    bs, be = base_sentiment(txt)
    if extra:
        for w, (d, wgt) in extra.items():
            if w in txt:
                if d > 0:
                    bs += wgt
                elif d < 0:
                    be += -wgt
    net = bs - be
    rel = relevant(txt)
    if not rel:
        return {"bull": bs, "bear": be, "net": 0, "relevance": False,
                "label": "irrelevant", "strength": 0}
    if net >= 2:
        label = "bull"
    elif net <= -2:
        label = "bear"
    else:
        label = "neutral"
    return {"bull": bs, "bear": be, "net": net, "relevance": True,
            "label": label, "strength": max(-6, min(6, net))}


def token_candidates(txt):
    """从一段中文文本提取候选学习词（2~6 字 n-gram，含停用字/碎词的丢弃）。

    返回去重后的词列表。只在 screening 学习时使用。
    """
    out = []
    for run in _HANZI.findall(txt or ""):
        n = len(run)
        for size in range(2, min(7, n) + 1):
            for i in range(0, n - size + 1):
                w = run[i:i + size]
                if any(c in _STOP_CHARS for c in w):
                    continue
                if w in _STOP_WORDS or w in out:
                    continue
                # 太通用的“一/二/…”数字串也不学
                if w.isdigit():
                    continue
                out.append(w)
    return out


def is_base_word(w):
    """该词是否已在基础词典中（学习词不与基础词典重复叠加）。"""
    if not w:
        return True
    return w in BULL_STRONG or w in BULL_WEAK or \
        w in BEAR_STRONG or w in BEAR_WEAK
